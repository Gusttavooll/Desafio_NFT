import { expect, test } from '@playwright/test'

test('carrinho persiste, cota, aplica cupom e remove sem perder precisão', async ({ page }) => {
  await page.goto('/cart')
  await expect(page.getByRole('heading', { name: 'Seu carrinho está vazio.' })).toBeVisible()
  await page.evaluate(async () => {
    const { items } = await (await fetch('/api/nfts?pageSize=100')).json()
    const nft = items.find((item: { id: string }) => item.id === 'emerald-ape-042')
    await fetch('/api/cart/items', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ nftId: nft.id, editionId: nft.editions[1].id, quantity: 1 }) })
  })
  await page.reload()
  const items = page.getByRole('region', { name: 'Itens do carrinho', exact: true })
  await expect(items.getByRole('heading', { name: 'Emerald Ape', exact: true })).toBeVisible()
  await expect(items.getByText('Total da linha:', { exact: false })).toBeVisible()
  await items.getByRole('button', { name: 'Aumentar quantidade emerald ape' }).click()
  await expect(items.getByRole('status', { name: 'Quantidade Emerald Ape' })).toHaveText('2')
  await page.getByRole('textbox', { name: 'Cupom', exact: true }).fill('KRONOS10')
  await page.getByRole('button', { name: 'Aplicar cupom', exact: true }).click()
  await expect(page.getByText('Desconto (KRONOS10)', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('textbox', { name: 'Cupom', exact: true })).toHaveValue('KRONOS10')
  await expect(items.getByRole('status', { name: 'Quantidade Emerald Ape' })).toHaveText('2')
  await page.getByRole('textbox', { name: 'Cupom', exact: true }).fill('INVALIDO')
  await page.getByRole('button', { name: 'Aplicar cupom', exact: true }).click()
  await expect(page.getByText('Cupom inválido.', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Revise o carrinho para continuar' })).toBeDisabled()
  await page.getByRole('button', { name: 'Remover cupom', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Conectar e finalizar' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await items.getByRole('button', { name: 'Remover Emerald Ape', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Seu carrinho está vazio.' })).toBeVisible()
})
