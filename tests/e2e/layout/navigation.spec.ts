import { expect, test } from '@playwright/test'

test('layout, navegação e conta mantêm um main e não transbordam', async ({ page }, info) => {
  await page.goto('/')
  await expect(page.getByRole('main')).toHaveCount(1)
  await expect(page.getByRole('link', { name: 'Kronos Archive, início' })).toBeVisible()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: 'Pular para o conteúdo' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('main')).toBeFocused()
  const nav = page.getByRole('navigation', { name: info.project.name === 'mobile' ? 'Navegação mobile' : 'Navegação principal', exact: true })
  await nav.getByRole('link', { name: 'Carrinho', exact: true }).click()
  await expect(page).toHaveURL(/\/cart$/)
  await page.goto('/profile')
  await page.getByLabel('E-mail', { exact: true }).fill('ana@kronos.test')
  await page.getByLabel('Senha', { exact: true }).fill('Colecionador#1')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await page.getByRole('navigation', { name: 'Minha conta', exact: true }).getByRole('link', { name: 'Carteiras', exact: true }).click()
  await expect(page).toHaveURL(/\/wallets$/)
  await expect(page.getByRole('main')).toHaveCount(1)
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
  expect(overflow).toBe(false)
})

test('Entrar no cabeçalho preserva caminho, filtros e âncora após autenticar', async ({ page }) => {
  await page.goto('/?q=%23101&collection=primatas-esmeralda&sort=recent&page=1#acervo')
  await expect(page.getByRole('searchbox', { name: 'Buscar obras' })).toHaveValue('#101')
  const previous = new URL(page.url())
  await page.getByRole('banner').getByRole('link', { name: 'Entrar', exact: true }).click()
  expect(new URL(page.url()).searchParams.get('returnTo')).toBe(`${previous.pathname}${previous.search}${previous.hash}`)
  await page.getByLabel('E-mail', { exact: true }).fill('ana@kronos.test')
  await page.getByLabel('Senha', { exact: true }).fill('Colecionador#1')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(previous.href)
  await expect(page.getByRole('searchbox', { name: 'Buscar obras' })).toHaveValue('#101')
})
