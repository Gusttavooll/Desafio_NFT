test('sessão expirada abre um único login e retorna ao perfil após autenticar', async ({ page }) => {
  await login(page)
  await expect(page.getByLabel('Nome de exibição', { exact: true })).toHaveValue('Ana Prado')
  const save = page.getByRole('button', { name: 'Salvar perfil', exact: true })
  await save.scrollIntoViewIfNeeded()
  await expect(save).toBeEnabled()
  // A troca do cenário e o envio usam o mesmo turno do navegador. Uma consulta
  // já em curso também pode provocar o 401 sem desmontar o botão antes do envio.
  await save.evaluate(button => {
    ;(window as unknown as { __mocks: { setScenario: (scenario: string) => void } }).__mocks.setScenario('session-expired')
    ;(button as HTMLButtonElement).click()
  })
  await expect(page.getByRole('dialog')).toHaveCount(1)
  await expect(page.getByText('Sua sessão expirou. Entre novamente para retomar o que estava fazendo.', { exact: true })).toBeVisible()
  await page.getByLabel('E-mail', { exact: true }).fill('ana@kronos.test')
  await page.getByLabel('Senha', { exact: true }).fill('Colecionador#1')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/profile$/)
  await expect(page.getByLabel('Nome de exibição', { exact: true })).toHaveValue('Ana Prado')
})

test('modal mantém foco, fecha com Esc, adapta ao mobile e bloqueia retorno externo', async ({ page }, info) => {
  await page.goto('/login?returnTo=%2Fcart')
  const dialog = page.getByRole('dialog')
  await expect(page.getByLabel('E-mail', { exact: true })).toBeFocused()
  for (let index = 0; index < 12; index++) {
    await page.keyboard.press('Tab')
    await expect(dialog.locator(':focus')).toHaveCount(1)
  }
  await page.getByLabel('Senha', { exact: true }).fill('Visivel#2026')
  await page.getByRole('button', { name: 'Mostrar senha', exact: true }).click()
  await expect(page.getByLabel('Senha', { exact: true })).toHaveAttribute('type', 'text')
  await page.screenshot({ path: info.outputPath('login.png'), fullPage: true, animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  if (info.project.name === 'mobile') expect((await dialog.boundingBox())?.width).toBe(390)
  await page.keyboard.press('Escape')
  await expect(page).toHaveURL(/\/cart$/)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.goto('/login?returnTo=https%3A%2F%2Fevil.test')
  await page.getByRole('button', { name: 'Fechar', exact: true }).click()
  await expect(page).toHaveURL(/\/$|\/\?q=/)
  for (const path of ['/profile', '/wallets', '/checkout']) {
    await page.goto(path)
    await expect(page.getByRole('dialog')).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page).toHaveURL(/\/$|\/\?q=/)
    await expect(page.getByRole('dialog')).toHaveCount(0)
  }
})
