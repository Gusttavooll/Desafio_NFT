import { expect, test, type Page } from '@playwright/test'

async function login(page: Page, returnTo = '/profile', email = 'ana@kronos.test', password = 'Colecionador#1') {
  await page.goto(`/login?returnTo=${encodeURIComponent(returnTo)}`)
  await page.getByLabel('E-mail', { exact: true }).fill(email)
  await page.getByLabel('Senha', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
}
async function scenario(page: Page, value: string) { await page.evaluate(value => (window as unknown as { __mocks: { setScenario: (scenario: string) => void } }).__mocks.setScenario(value), value) }

test('login trata falha, retoma rota e isola dados após sair e trocar usuário', async ({ page }) => {
  await page.goto('/login?returnTo=%2Fprofile')
  await page.getByLabel('E-mail', { exact: true }).fill('ana@kronos.test')
  await page.getByLabel('Senha', { exact: true }).fill('SenhaErrada#1')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('E-mail ou senha incorretos.')
  await page.getByLabel('Senha', { exact: true }).fill('Colecionador#1')
  await scenario(page, 'server-error')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Serviço indisponível')
  await expect(page.getByLabel('E-mail', { exact: true })).toHaveValue('ana@kronos.test')
  await scenario(page, 'success')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/profile$/)
  await expect(page.getByLabel('Nome de exibição', { exact: true })).toHaveValue('Ana Prado')
  await page.reload()
  await expect(page.getByLabel('E-mail', { exact: true })).toHaveValue('ana@kronos.test')
  await page.getByRole('button', { name: 'Sair da conta' }).click()
  await expect(page).not.toHaveURL(/\/profile$/)
  await login(page, '/profile', 'bruno@kronos.test', 'Colecionador#2')
  await expect(page.getByLabel('Nome de exibição', { exact: true })).toHaveValue('Bruno Leal')
  await expect(page.getByLabel('E-mail', { exact: true })).toHaveValue('bruno@kronos.test')
  await page.getByRole('navigation', { name: 'Minha conta', exact: true }).getByRole('link', { name: 'Carteiras', exact: true }).click()
  await expect(page.getByLabel('Endereço da carteira', { exact: true })).toHaveCount(0)
  await expect(page.getByText('Ana Prado', { exact: true })).toHaveCount(0)
})

test('cadastro associa erros aos campos, resolve conflito e não persiste senha em claro', async ({ page }) => {
  await page.goto('/register?returnTo=%2Fprofile')
  await page.getByRole('button', { name: 'Criar perfil', exact: true }).click()
  await expect(page.getByLabel('E-mail', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await page.getByLabel('Nome de exibição', { exact: true }).fill('Eva Arquivo')
  await page.getByLabel('Nome de usuário', { exact: true }).fill('eva.arquivo')
  await page.getByLabel('E-mail', { exact: true }).fill('eva@kronos.test')
  await page.getByLabel('Senha', { exact: true }).fill('Ficticia#2026')
  await page.getByLabel('Confirmar senha', { exact: true }).fill('Diferente#2026')
  await page.getByRole('button', { name: 'Criar perfil', exact: true }).click()
  await expect(page.getByText('As senhas não coincidem.')).toBeVisible()
  await page.getByLabel('Confirmar senha', { exact: true }).fill('Ficticia#2026')
  await scenario(page, 'register-conflict')
  await page.getByRole('button', { name: 'Criar perfil', exact: true }).click()
  await expect(page.getByText('Este e-mail já está cadastrado.', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Nome de exibição', { exact: true })).toHaveValue('Eva Arquivo')
  await scenario(page, 'success')
  await page.getByRole('button', { name: 'Criar perfil', exact: true }).click()
  await expect(page).toHaveURL(/\/profile$/)
  await expect(page.getByLabel('Nome de exibição', { exact: true })).toHaveValue('Eva Arquivo')
  expect(await page.evaluate(() => JSON.stringify(localStorage))).not.toContain('Ficticia#2026')
})

