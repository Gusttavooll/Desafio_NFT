import { expect, test } from '@playwright/test'

test('explorar, filtrar, paginar e abrir a obra com precisão ETH', async ({ page }, info) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'ARTE QUE ATRAVESSA O TEMPO.' })).toBeVisible()
  await expect(page.locator('.nft-card')).toHaveCount(3)
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: `../outputs/landing-${info.project.name}.png`, fullPage: true, animations: 'disabled' })
  await page.getByRole('link', { name: 'Explorar o acervo', exact: true }).click()
  await expect(page).toHaveURL(/#acervo$/)
  await page.getByRole('button', { name: 'Próxima', exact: true }).click()
  await expect(page.locator('.nft-card').first()).toContainText('Field notes 004')
  await page.getByRole('button', { name: /Sistemas generativos/ }).click()
  await expect(page).toHaveURL(/page=1/)
  await expect(page.locator('.nft-card')).toHaveCount(3)
  await page.getByRole('searchbox', { name: 'Buscar obras' }).fill('residue')
  await expect(page.locator('.nft-card')).toHaveCount(1)
  await page.reload()
  await expect(page.getByRole('searchbox')).toHaveValue('residue')
  await expect(page.locator('.nft-card')).toHaveCount(1)
  await page.getByRole('searchbox').fill('inexistente')
  await expect(page.getByRole('heading', { name: 'Nenhuma obra encontrada.' })).toBeVisible()
  await page.getByRole('button', { name: 'Limpar filtros' }).click()
  await expect(page.locator('.nft-card')).toHaveCount(3)
  await page.getByLabel('Ordenar obras').selectOption('title')
  await expect(page.locator('.nft-card').first()).toContainText('Chromatic interval')
  await page.goto('/nfts/k-001')
  await expect(page.getByRole('heading', { name: 'Phase shift 001' })).toBeVisible()
  await expect(page.locator('.price-tag')).toContainText('0.420000000000000001')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Phase shift 001' })).toBeVisible()
  await page.goto('/nfts/inexistente')
  await expect(page.getByRole('heading', { name: 'Obra não encontrada.' })).toBeVisible()
})

