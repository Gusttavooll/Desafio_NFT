import { expect, test } from '@playwright/test'

test('explorar, filtrar, paginar e abrir obras do catálogo compartilhado', async ({ page }, info) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'ARTE QUE ATRAVESSA O TEMPO.' })).toBeVisible()
  await expect(page.locator('.nft-card')).toHaveCount(3)
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: info.outputPath('landing.png'), fullPage: true, animations: 'disabled' })
  await page.getByRole('link', { name: 'Explorar o acervo', exact: true }).click()
  await expect(page).toHaveURL(/#acervo$/)
  await page.getByRole('button', { name: 'Próxima', exact: true }).click()
  await expect(page).toHaveURL(/page=2/)
  await expect(page.locator('.nft-card')).toHaveCount(3)
  await page.getByRole('button', { name: /Primatas Esmeralda/ }).click()
  await expect(page).toHaveURL(/page=1/)
  await expect(page.locator('.nft-card')).toHaveCount(3)
  await page.getByRole('searchbox', { name: 'Buscar obras' }).fill('#101')
  await expect(page.locator('.nft-card')).toHaveCount(1)
  await page.reload()
  await expect(page.getByRole('searchbox')).toHaveValue('#101')
  await expect(page.locator('.nft-card')).toHaveCount(1)
  await page.getByRole('searchbox').fill('inexistente')
  await expect(page.getByRole('heading', { name: 'Nenhuma obra encontrada.' })).toBeVisible()
  await page.getByRole('button', { name: 'Limpar filtros' }).click()
  await expect(page.locator('.nft-card')).toHaveCount(3)
  await page.getByLabel('Ordenar obras').selectOption('price-asc')
  await expect(page.locator('.nft-card').first()).toContainText('Neon Vessel')
  await page.goto('/nfts/emerald-ape-042')
  await expect(page.getByRole('heading', { name: 'Emerald Ape', exact: true })).toBeVisible()
  await expect(page.locator('.price-tag')).toContainText('1.850')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Emerald Ape', exact: true })).toBeVisible()
  await page.goto('/nfts/inexistente')
  await expect(page.getByRole('heading', { name: 'Obra não encontrada.' })).toBeVisible()
})

test('layout sem overflow e sem movimento obrigatório', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.locator('.nft-card')).toHaveCount(3)
  for (const width of [390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await page.locator('.nft-card').last().scrollIntoViewIfNeeded()
  await expect.poll(() => page.locator('img').evaluateAll(images => images.every(image => image.complete && image.naturalWidth > 0))).toBe(true)
})

test('cenários vazio e falha do core chegam à landing', async ({ page }) => {
  await page.goto('/?scenario=empty')
  await expect(page.getByRole('heading', { name: 'Nenhuma obra encontrada.' })).toBeVisible()
  await page.goto('/?scenario=server-error')
  await expect(page.getByRole('heading', { name: 'Não foi possível abrir o acervo.' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Tentar novamente', exact: true })).toBeVisible()
  await page.goto('/?scenario=success')
  await expect(page.locator('.nft-card')).toHaveCount(3)
})
