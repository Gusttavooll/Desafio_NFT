import { expect, test } from '@playwright/test'

test('favoritos retomam a obra após login, persistem, revertem falha e isolam contas', async ({ page }) => {
  const favorite = page.locator('.detail-copy').getByRole('button', { name: /Favoritar obra|Remover dos favoritos/ })
  await page.goto('/nfts/emerald-ape-042')
  await favorite.click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByLabel('E-mail', { exact: true }).fill('ana@kronos.test')
  await page.getByLabel('Senha', { exact: true }).fill('Colecionador#1')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/nfts\/emerald-ape-042$/)
  await favorite.click()
  await expect(favorite).toHaveAttribute('aria-pressed', 'true')
  await expect(favorite).toBeEnabled()
  await page.reload()
  await expect(favorite).toHaveAttribute('aria-pressed', 'true')
  await page.evaluate(() => (window as unknown as { __mocks: { setScenario: (name: string) => void } }).__mocks.setScenario('server-error'))
  await favorite.click()
  await expect(page.locator('.detail-copy').getByRole('alert')).toBeVisible()
  await expect(favorite).toHaveAttribute('aria-pressed', 'true')
  await page.evaluate(() => (window as unknown as { __mocks: { setScenario: (name: string) => void } }).__mocks.setScenario('success'))
  await page.goto('/profile')
  await page.getByRole('button', { name: 'Sair da conta' }).click()
  await page.goto('/login?returnTo=%2Fnfts%2Femerald-ape-042')
  await page.getByLabel('E-mail', { exact: true }).fill('bruno@kronos.test')
  await page.getByLabel('Senha', { exact: true }).fill('Colecionador#2')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/nfts\/emerald-ape-042$/)
  await expect(favorite).toHaveAttribute('aria-pressed', 'false')
})

test('favorito iniciado no catálogo retorna à mesma busca e aos mesmos filtros', async ({ page }) => {
  await page.goto('/?q=%23101&collection=primatas-esmeralda&sort=recent&page=1#acervo')
  const card = page.locator('.nft-card').first()
  await expect(card).toBeVisible()
  const previous = new URL(page.url())
  await card.getByRole('button', { name: 'Favoritar obra', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  expect(new URL(page.url()).searchParams.get('returnTo')).toBe(`${previous.pathname}${previous.search}${previous.hash}`)
  await page.getByLabel('E-mail', { exact: true }).fill('ana@kronos.test')
  await page.getByLabel('Senha', { exact: true }).fill('Colecionador#1')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(previous.href)
  await expect(page.getByRole('searchbox', { name: 'Buscar obras' })).toHaveValue('#101')
  await card.getByRole('button', { name: 'Favoritar obra', exact: true }).click()
  await expect(card.getByRole('button', { name: 'Remover dos favoritos', exact: true })).toHaveAttribute('aria-pressed', 'true')
})
