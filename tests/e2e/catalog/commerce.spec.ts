import { expect, test } from '@playwright/test'
import { closeFilters, openFilters } from './filter-controls'

test('edição, quantidade, carrinho e galeria funcionam pelo detalhe', async ({ page }) => {
  await page.goto('/nfts/emerald-ape-042')
  await expect(page.getByRole('heading', { name: 'Emerald Ape', exact: true, level: 1 })).toBeVisible()
  await page.getByRole('button', { name: 'Ver imagem 2' }).click()
  await expect(page.getByRole('button', { name: 'Ver imagem 2' })).toHaveAttribute('aria-pressed', 'true')
  await page.locator('input[name="edition"][value$="1-10"]').check()
  await page.getByRole('button', { name: 'Aumentar quantidade da obra' }).click()
  await page.getByRole('button', { name: 'Adicionar ao carrinho' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'unidades adicionadas' })).toContainText('2 unidades adicionadas')
  await page.getByRole('link', { name: 'Ver carrinho →' }).click()
  await expect(page.getByRole('heading', { name: 'Carrinho', exact: true })).toBeVisible()
  await expect(page.getByRole('group', { name: 'Quantidade Emerald Ape' })).toContainText('2')
  await page.reload()
  await expect(page.getByRole('group', { name: 'Quantidade Emerald Ape' })).toContainText('2')
})

test('filtros de rede e preço compõem a URL e rejeitam intervalo invertido', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.nft-card')).toHaveCount(3)
  await openFilters(page)
  await page.getByLabel('Filtrar rede').selectOption('polygon')
  await page.getByLabel('Preço mínimo em ETH').fill('0.2')
  await page.getByLabel('Preço máximo em ETH').fill('0.4')
  await page.getByRole('button', { name: 'Aplicar preços' }).click()
  await expect(page).toHaveURL(/network=polygon/)
  await expect(page).toHaveURL(url => JSON.parse(url.searchParams.get('maxPrice') ?? 'null') === '0.4')
  await closeFilters(page)
  await expect(page.locator('.nft-card').first()).toContainText('polygon')
  await page.reload()
  await openFilters(page)
  await expect(page.getByLabel('Preço máximo em ETH')).toHaveValue('0.4')
  await page.getByLabel('Preço mínimo em ETH').fill('1')
  await page.getByRole('button', { name: 'Aplicar preços' }).click()
  await expect(page.getByRole('alert')).toContainText('mínimo')
  await closeFilters(page)
})
