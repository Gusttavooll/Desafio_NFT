import { expect, test } from '@playwright/test'
import { closeFilters, openFilters } from './filter-controls'

test('destaques independentes e múltiplas coleções persistem na URL', async ({ page }) => {
  await page.goto('/')
  const hero = page.locator('.hero-art')
  await expect(hero).toBeVisible()
  const first = await hero.getAttribute('href')
  await page.getByRole('button', { name: 'Próximo destaque', exact: true }).click()
  await expect(hero).not.toHaveAttribute('href', first!)
  const next = await hero.getAttribute('href')
  await page.getByRole('searchbox', { name: 'Buscar obras' }).fill('inexistente')
  await expect(page.getByRole('heading', { name: 'Nenhuma obra encontrada.' })).toBeVisible()
  await expect(hero).toHaveAttribute('href', next!)
  await page.getByRole('button', { name: 'Limpar filtros', exact: true }).click()
  await openFilters(page)
  const primates = page.getByRole('button', { name: /Primatas Esmeralda/ })
  const nomads = page.getByRole('button', { name: /Nômades/ })
  await primates.click()
  await expect(primates).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.collection-results')).toHaveAttribute('aria-busy', 'false')
  await nomads.click()
  await expect(nomads).toHaveAttribute('aria-pressed', 'true')
  await expect(primates).toHaveAttribute('aria-pressed', 'true')
  await expect.poll(() => new URL(page.url()).searchParams.get('collection')).toContain('nomades,primatas-esmeralda')
  await page.reload()
  await openFilters(page)
  await expect(primates).toHaveAttribute('aria-pressed', 'true')
  await expect(nomads).toHaveAttribute('aria-pressed', 'true')
  await primates.click()
  await expect(primates).toHaveAttribute('aria-pressed', 'false')
  await expect(nomads).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: /Todas as obras/ }).click()
  await expect(nomads).toHaveAttribute('aria-pressed', 'false')
  await closeFilters(page)
  if ((page.viewportSize()?.width ?? 1440) <= 640) {
    await openFilters(page)
    await page.keyboard.press('Tab')
    await expect(page.getByRole('dialog', { name: 'Filtros do acervo' }).locator(':focus')).toHaveCount(1)
    await page.keyboard.press('Escape')
    await expect(page.getByRole('dialog', { name: 'Filtros do acervo' })).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'Abrir filtros', exact: true })).toBeFocused()
    await expect(page.getByRole('group', { name: 'Recorte do acervo' })).toBeVisible()
  }
})
