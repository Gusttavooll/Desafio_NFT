import { expect, test } from '@playwright/test'

test('cadastra, valida e persiste principal e secundária ligada', async ({ page }) => {
  await page.goto('/wallets')
  await expect(page).toHaveURL(/\/login/)
  await page.getByLabel('E-mail', { exact: true }).fill('bruno@kronos.test')
  await page.getByLabel('Senha', { exact: true }).fill('Colecionador#2')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/wallets$/)
  const primary = page.locator('#wallet-primary')
  await expect(primary.getByLabel('Nome de exibição *')).toHaveValue('Bruno Leal')
  await primary.getByLabel('Endereço da carteira *').fill('endereço inválido')
  await primary.getByRole('button', { name: 'Salvar carteira principal' }).click()
  await expect(primary.getByText('Use 0x seguido de 40 caracteres hexadecimais.')).toBeVisible()
  await expect(primary.getByLabel('Endereço da carteira *')).toBeFocused()
  await primary.getByLabel('Endereço da carteira *').fill(`0x${'b'.repeat(40)}`)
  await primary.getByLabel('Apelido *').fill('Arquivo de Bruno')
  await primary.getByRole('button', { name: 'Salvar carteira principal' }).click()
  await expect(primary.getByRole('status')).toContainText('Carteira salva')
  await page.getByRole('button', { name: 'Adicionar carteira secundária' }).click()
  const secondary = page.locator('#wallet-secondary')
  await secondary.getByLabel('Igual à carteira principal').check()
  await secondary.getByRole('button', { name: 'Salvar carteira secundária' }).click()
  await expect(secondary.getByRole('status')).toContainText('Carteira salva')
  await primary.getByLabel('Apelido *').fill('Arquivo atualizado')
  await primary.getByRole('button', { name: 'Salvar carteira principal' }).click()
  await expect(secondary.getByLabel('Apelido *')).toHaveValue('Arquivo atualizado')
  await page.reload()
  await expect(primary.getByLabel('Apelido *')).toHaveValue('Arquivo atualizado')
  await expect(secondary.getByLabel('Igual à carteira principal')).toBeChecked()
  await expect(secondary.getByLabel('Endereço da carteira *')).toHaveValue(`0x${'b'.repeat(40)}`)
  for (const width of [390, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
})
